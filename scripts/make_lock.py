"""Write requirements-lock.txt: the exact installed version of every package in requirements.txt
and of everything those packages need, read from the installed package metadata.

    python -B scripts/make_lock.py [--out requirements-lock.txt]

requirements.txt keeps lower bounds so the code installs on newer versions; the lock file records
the versions the results were produced with. Dependencies that apply only on another platform (an
environment marker that is false here) are left out, so regenerate the file on the machine whose
environment you want to record.
"""

from __future__ import annotations

import argparse
import os
import platform
import sys
from importlib import metadata

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def top_level(path: str) -> list[Requirement]:
    """The requirements named in requirements.txt (comments and blank lines skipped)."""
    reqs = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                reqs.append(Requirement(line))
    return reqs


def applies(req: Requirement, extras: set[str]) -> bool:
    """Whether a dependency applies on this platform for the requested extras."""
    if req.marker is None:
        return True
    return any(req.marker.evaluate({"extra": e}) for e in (extras or {""}))


def resolve(roots: list[Requirement]) -> dict[str, str]:
    """Walk the installed metadata from the roots; return {distribution name: version}."""
    found: dict[str, str] = {}
    seen: set[tuple[str, frozenset[str]]] = set()
    todo = [(r.name, frozenset(r.extras)) for r in roots]
    while todo:
        name, extras = todo.pop()
        key = (canonicalize_name(name), extras)
        if key in seen:
            continue
        seen.add(key)
        try:
            dist = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            sys.exit(f"{name} is required but not installed; install requirements.txt first")
        found[dist.metadata["Name"]] = dist.version
        for spec in dist.requires or []:
            req = Requirement(spec)
            if applies(req, set(extras)):
                todo.append((req.name, frozenset(req.extras)))
    return found


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", default=os.path.join(ROOT, "requirements-lock.txt"))
    args = ap.parse_args()

    pins = resolve(top_level(os.path.join(ROOT, "requirements.txt")))
    lines = [
        "# Exact versions the results were produced with: requirements.txt and everything it needs.",
        "# Generated by scripts/make_lock.py from the installed packages; do not edit by hand.",
        f"# Python {platform.python_version()} on {platform.system()} {platform.release()} "
        f"({platform.machine()}).",
        "# Install with: pip install -r requirements-lock.txt",
    ]
    lines += [f"{name}=={pins[name]}" for name in sorted(pins, key=canonicalize_name)]
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(pins)} pins to {args.out}")


if __name__ == "__main__":
    main()
